# Function to plot individual forecasts
def plot_individual_forecasts(train, test, ar_forecast, arma_forecast, arima_forecast, name, steps=10):
    try:
        models = {'AR': ar_forecast, 'ARMA': arma_forecast, 'ARIMA': arima_forecast}
        for model_name, forecast in models.items():
            if len(forecast) != steps or np.isnan(forecast).all():
                print(f"Warning: Invalid {model_name} forecast for {name}. Skipping plot.")
                continue
            plt.figure(figsize=(12, 6))
            plt.plot(train.index[-50:], train[-50:], label='Train', color='blue')
            plt.plot(test.index[:steps], test[:steps], label='Test', color='black')
            plt.plot(test.index[:steps], forecast, label=f'{model_name} Forecast', color='red')
            plt.title(f'{model_name} Forecasting for {name}')
            plt.xlabel('Time')
            plt.ylabel('Price')
            plt.grid(True)
            plt.legend()
            filename = f'{name}_{model_name}_forecast.png'
            plt.savefig(filename)
            plt.close()
            print(f"Saved plot: {filename}")
    except Exception as e:
        print(f"Warning: Failed to plot individual forecasts for {name}: {str(e)}")

# Main execution
def main():
    try:
        # Load data
        apple_df, msft_df = load_stock_data()
        apple_close = apple_df['Close']
        msft_close = msft_df['Close']

        # Ensure datetime indices
        apple_df, apple_close = ensure_datetime_index(apple_df, apple_close, "Apple Close")
        msft_df, msft_close = ensure_datetime_index(msft_df, msft_close, "Microsoft Close")

        # Stationarity tests
        apple_series, apple_is_diff = stationarity_tests(apple_close, "Apple Close")
        msft_series, msft_is_diff = stationarity_tests(msft_close, "Microsoft Close")

        # Cointegration test
        apple_series, msft_series = cointegration_test(apple_series, msft_series, "Apple Close", "Microsoft Close")

        # Fit models and forecast
        apple_train, apple_test, apple_ar, apple_arma, apple_arima, apple_steps = fit_and_forecast(apple_series, "Apple Close")
        msft_train, msft_test, msft_ar, msft_arma, msft_arima, msft_steps = fit_and_forecast(msft_series, "Microsoft Close")

        # Individual forecast plots
        if apple_train is not None:
            plot_individual_forecasts(apple_train, apple_test, apple_ar, apple_arma, apple_arima, "Apple Close", apple_steps)
        if msft_train is not None:
            plot_individual_forecasts(msft_train, msft_test, msft_ar, msft_arma, msft_arima, "Microsoft Close", msft_steps)

        # Combined graph
        plot_combined_graph(
            apple_close, apple_series if apple_is_diff else None, apple_is_diff,
            msft_close, msft_series if msft_is_diff else None, msft_is_diff,
            apple_train, apple_test, apple_ar, apple_arma, apple_arima, apple_steps,
            msft_train, msft_test, msft_ar, msft_arma, msft_arima, msft_steps
        )

        # List saved plots
        print("\nSaved Plots:")
        saved_files = [f for f in os.listdir() if f.endswith('.png')]
        for f in saved_files:
            print(f"- {f}")
        if not saved_files:
            print("No plots were saved.")
    except Exception as e:
        print(f"Error in main execution: {str(e)}")

if __name__ == "__main__":
    main()

