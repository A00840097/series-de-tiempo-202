            for col in datetime_cols:
                if col in df.columns:
                    df[col] = pd.to_datetime(df[col], errors='coerce')
                    if df[col].isna().all():
                        raise ValueError(f"Invalid datetime values in {col} for {name}.")
                    df.set_index(col, inplace=True)
                    series.index = df.index
                    break
            else:
                print(f"Warning: No datetime column found for {name}. Using default index.")
