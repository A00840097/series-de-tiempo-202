import pandas as pd
import numpy as np
from statsmodels.tsa.ar_model import AutoReg
from statsmodels.tsa.arima.model import ARIMA
from statsmodels.tsa.stattools import adfuller, kpss, coint
from statsmodels.tsa.api import ARMA
import matplotlib.pyplot as plt
from google.colab import files
import warnings
warnings.filterwarnings("ignore")

# Function to upload and read Excel files
def load_stock_data():
    print("Upload APPLE 1 MIN.xlsx")
    uploaded = files.upload()
    apple_df = pd.read_excel(list(uploaded.keys())[0])
    print("Upload MICROSOFT 1 MIN.xlsx")
    uploaded = files.upload()
    msft_df = pd.read_excel(list(uploaded.keys())[0])
    return apple_df, msft_df

# Function to perform stationarity tests
def stationarity_tests(series, name):
    print(f"\nStationarity Tests for {name}")
    # ADF Test
    adf_result = adfuller(series, autolag='AIC')
    print(f"ADF Test p-value: {adf_result[1]}")
    # KPSS Test
    kpss_result = kpss(series, regression='c')
    print(f"KPSS Test p-value: {kpss_result[1]}")
    # If non-stationary, difference the series
    if adf_result[1] > 0.05 or kpss_result[1] < 0.05:
        print(f"{name} is non-stationary. Differencing...")
        return series.diff().dropna()
    return series

# Function to perform cointegration test
def cointegration_test(series1, series2, name1, name2):
    print(f"\nCointegration Test between {name1} and {name2}")
    score, p_value, _ = coint(series1, series2)
    print(f"Engle-Granger Cointegration Test p-value: {p_value}")
    if p_value < 0.05:
        print("Series are cointegrated")
    else:
        print("Series are not cointegrated")

# Function to fit and forecast models
def fit_and_forecast(series, name, steps=10):
    print(f"\nFitting Models for {name}")

    # Prepare data
    series = series.dropna()
    train_size = int(len(series) * 0.8)
    train, test = series[:train_size], series[train_size:]

    # AR Model
    ar_model = AutoReg(train, lags=1).fit()
    ar_forecast = ar_model.forecast(steps=steps)
    print("AR Model Summary:")
    print(ar_model.summary())

    # ARMA Model (p=1, q=1)
    arma_model = ARMA(train, order=(1, 1)).fit()
    arma_forecast = arma_model.forecast(steps=steps)
    print("ARMA Model Summary:")
    print(arma_model.summary())

    # ARIMA Model (p=1, d=1, q=1)
    arima_model = ARIMA(train, order=(1, 1, 1)).fit()
    arima_forecast = arima_model.forecast(steps=steps)
    print("ARIMA Model Summary:")
    print(arima_model.summary())

    # Plot forecasts
    plt.figure(figsize=(12, 6))
    plt.plot(train.index[-50:], train[-50:], label='Train')
    plt.plot(test.index[:steps], test[:steps], label='Test')
    plt.plot(test.index[:steps], ar_forecast, label='AR Forecast')
    plt.plot(test.index[:steps], arma_forecast, label='ARMA Forecast')
    plt.plot(test.index[:steps], arima_forecast, label='ARIMA Forecast')
    plt.title(f'Forecasting for {name}')
    plt.legend()
    plt.savefig(f'{name}_forecast.png')
    plt.close()

# Main execution
def main():
    # Load data
    apple_df, msft_df = load_stock_data()

    # Extract closing prices
    apple_close = apple_df['Close']
    msft_close = msft_df['Close']

    # Ensure indices are datetime (if not already)
    if not pd.api.types.is_datetime64_any_dtype(apple_df.index):
        apple_close.index = pd.to_datetime(apple_df.index)
    if not pd.api.types.is_datetime64_any_dtype(msft_df.index):
        msft_close.index = pd.to_datetime(msft_df.index)

    # Stationarity tests
    apple_close = stationarity_tests(apple_close, "Apple Close")
    msft_close = stationarity_tests(msft_close, "Microsoft Close")

    # Cointegration test
    cointegration_test(apple_close, msft_close, "Apple Close", "Microsoft Close")

    # Fit models and forecast
    fit_and_forecast(apple_close, "Apple Close")
    fit_and_forecast(msft_close, "Microsoft Close")

    # Display saved plots
    print("\nForecast plots saved as 'Apple Close_forecast.png' and 'Microsoft Close_forecast.png'")

