# Function to perform stationarity test (ADF test)
def adf_test(series, title=''):
    result = adfuller(series.dropna())
    print(f'ADF Test for {title}:')
    print(f'ADF Statistic: {result[0]}')
    print(f'p-value: {result[1]}')
    print('Stationary' if result[1] < 0.05 else 'Non-Stationary')
    print('')

# Function to perform cointegration test
def cointegration_test(series1, series2, name1='Series1', name2='Series2'):
    score, p_value, _ = coint(series1, series2)
    print(f'Cointegration Test between {name1} and {name2}:')
    print(f'Cointegration Test Statistic: {score}')
    print(f'p-value: {p_value}')
    print('Cointegrated' if p_value < 0.05 else 'Not Cointegrated')
    print('')

# Function to fit and forecast models
def fit_and_forecast(series, name, steps=10):
    # AR Model
    ar_model = AutoReg(series, lags=1).fit()
    ar_forecast = ar_model.predict(start=len(series), end=len(series)+steps-1)

    # ARMA Model (using ARIMA with MA component)
    arma_model = ARIMA(series, order=(1,0,1)).fit()
    arma_forecast = arma_model.forecast(steps=steps)

    # ARIMA Model (auto_arima for optimal parameters)
    arima_model = pm.auto_arima(series, seasonal=False, stepwise=True, trace=False)
    arima_forecast = arima_model.predict(n_periods=steps)

    # Plotting forecasts
    plt.figure(figsize=(12,6))
    plt.plot(series[-50:], label='Historical Data')
    plt.plot(pd.date_range(start=series.index[-1], periods=steps+1, freq='T')[1:],
             ar_forecast, label='AR Forecast')
    plt.plot(pd.date_range(start=series.index[-1], periods=steps+1, freq='T')[1:],
             arma_forecast, label='ARMA Forecast')
    plt.plot(pd.date_range(start=series.index[-1], periods=steps+1, freq='T')[1:],
             arima_forecast, label='ARIMA Forecast')
    plt.title(f'Forecasting for {name}')
    plt.legend()
    plt.savefig(f'{name}_forecast.png')
    plt.show()

    return ar_forecast, arma_forecast, arima_forecast

