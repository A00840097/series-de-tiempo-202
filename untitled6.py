plt.xlabel("Time (Months)")
plt.ylabel("Treasury Bill Rates")
plt.title("TB3M & TB6M Treasury Bill Rates Over Time")
plt.xticks(rotation=45)  # Improve readability
plt.legend()
plt.show()

