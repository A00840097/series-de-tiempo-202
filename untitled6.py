# 📊 Fit ARIMA Model
def fit_arima(series, name):
    model = arima.ARIMA(series, order=(1,1,1))  # Adjust based on stationarity tests
    results = model.fit()
    print(f'\n⚙️ ARIMA Model Summary for {name}:')
    print(results.summary())
    return results

tb3m_arima = fit_arima(df["GS3M"], "TB3M (3-Month Rate)")
tb6m_arima = fit_arima(df["GS6M"], "TB6M (6-Month Rate)")

# 📈 Forecast Next Periods
def forecast_arima(model, steps, name):
    forecast = model.get_forecast(steps=steps)
    forecast_df = forecast.conf_int()
    forecast_df["Predicted"] = forecast.predicted_mean
    forecast_df.index = range(len(model.data.endog), len(model.data.endog) + steps)

    # 📉 Plot Forecast
    plt.figure(figsize=(10,5))
    plt.plot(model.data.endog, label="Actual Data", color="blue")
    plt.plot(forecast_df["Predicted"], label="Forecast", color="red")
    plt.fill_between(forecast_df.index, forecast_df.iloc[:,0], forecast_df.iloc[:,1], color="gray", alpha=0.2)
    plt.legend()
    plt.title(f"{name} - ARIMA Forecast ({steps} periods)")
    plt.show()

forecast_arima(tb3m_arima, 30, "TB3M (3-Month Rate)")  # Forecasting next 30 periods
forecast_arima(tb6m_arima, 30, "TB6M (6-Month Rate)")  # Forecasting next 30 periods