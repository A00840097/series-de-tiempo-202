import pandas as pd
import numpy as np
import statsmodels.api as sm
import statsmodels.tsa.stattools as ts
import statsmodels.tsa.vector_ar.vecm as vecm
import statsmodels.tsa.arima.model as arima
import matplotlib.pyplot as plt
from google.colab import files

# 📂 Upload the dataset manually
print("🔼 Upload 'Table 22.7 (1).txt' dataset")
uploaded = files.upload()
filename = list(uploaded.keys())[0]

# 📊 Load Data as Raw Text and Parse
with open(filename, "r") as file:
    lines = file.readlines()

# 📝 Manually Parse TXT Data
data = []
for line in lines[5:]:  # Skip header lines
    parts = line.split()  # Split by spaces
    if len(parts) >= 3:
        data.append(parts[:3])  # Keep first 3 columns: Date, GS3M, GS6M

# 📊 Convert to DataFrame
df = pd.DataFrame(data, columns=["Date", "GS3M", "GS6M"])
df["GS3M"] = pd.to_numeric(df["GS3M"], errors="coerce")
df["GS6M"] = pd.to_numeric(df["GS6M"], errors="coerce")
df.dropna(inplace=True)  # Remove bad rows

# ✅ Check structure
print("\n📌 Sample data preview:")
print(df.head())

# 📈 Plot TB3M & TB6M Time Series
plt.figure(figsize=(10,5))
