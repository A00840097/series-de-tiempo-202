# Ensure datetime index
def ensure_datetime_index(df, series, name):
    try:
        if not pd.api.types.is_datetime64_any_dtype(df.index):
            if 'Local Date' in df.columns:
                df['Local Date'] = pd.to_datetime(df['Local Date'], unit='D', origin='1899-12-30', errors='coerce')
                if df['Local Date'].isna().all():
                    raise ValueError(f"Invalid datetime values in Local Date for {name}.")
                df.set_index('Local Date', inplace=True)
                series.index = df.index
            else:
                print(f"Warning: No datetime column found for {name}. Using default index.")
                df.index = pd.RangeIndex(len(df))
                series.index = df.index
        return df, series
    except Exception as e:
        print(f"Warning: Failed to set datetime index for {name}: {str(e)}. Using default index.")
        df.index = pd.RangeIndex(len(df))
        series.index = df.index
        return df, series

