# Function to clean series (handle NaN/Inf)
def clean_series(series, name):
    try:
        print(f"Checking {name} for NaN/Inf values...")
        if not pd.api.types.is_numeric_dtype(series):
            raise ValueError(f"{name} contains non-numeric values.")
        if series.isna().any() or np.isinf(series).any():
            print(f"{name} contains NaN or Inf values. Cleaning...")
            series = series.fillna(method='ffill').fillna(method='bfill').dropna()
            series = series.replace([np.inf], series.max())
            series = series.replace([-np.inf], series.min())
        if series.isna().any():
            raise ValueError(f"{name} still contains NaN values after cleaning.")
        if len(series) == 0:
            raise ValueError(f"{name} is empty after cleaning.")
        print(f"{name} is clean with {len(series)} observations.")
        return series
    except Exception as e:
        raise ValueError(f"Failed to clean {name}: {str(e)}")

